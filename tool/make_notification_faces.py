"""Draws the five mood faces for the Android reminder notification.

The faces in the app are Material Symbols Rounded glyphs (weight 500) on a
mood-coloured disc (lib/ui/mood_style.dart, MoodFace). A notification layout
can't use the font, so this writes the same faces as vector drawables — light
colours in res/drawable, dark in res/drawable-night (the notification shade
follows the system theme).

Needs fontTools (`pip install fonttools`):
    python3 tool/make_notification_faces.py \
        ~/.pub-cache/hosted/pub.dev/material_symbols_icons-<ver>/lib/fonts/MaterialSymbolsRounded.ttf
"""

import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

# Mood value (5 = best) → glyph and colours. Keep in step with MoodStyle.
FACES = {
    5: ("rad", 0xE815, "#1FA85D", "#37CE78"),
    4: ("good", 0xE813, "#84CFA6", "#2E8650"),
    3: ("meh", 0xE812, "#8C857E", "#9A938C"),
    2: ("bad", 0xE811, "#BCA4E5", "#735E97"),
    1: ("awful", 0xE814, "#8559D0", "#A98CEE"),
}
ON_LIGHT, ON_DARK = "#FFFFFF", "#14100D"

SIZE = 48.0  # the disc
EM = SIZE * 0.72  # MoodFace draws the glyph at 72 % of the disc
PAD = (SIZE - EM) / 2


def face_path(font: TTFont, codepoint: int) -> str:
    glyphs = font.getGlyphSet()
    name = font.getBestCmap()[codepoint]
    upm = font["head"].unitsPerEm
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    k = EM / upm
    # Font units have y up from the baseline; the drawable has y down.
    glyphs[name].draw(TransformPen(pen, (k, 0, 0, -k, PAD, PAD + EM)))
    return pen.getCommands()


def drawable(path: str, disc: str, ink: str) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/make_notification_faces.py — do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="48dp"
    android:height="48dp"
    android:viewportWidth="48"
    android:viewportHeight="48">
    <path
        android:fillColor="{disc}"
        android:pathData="M24,0a24,24 0,1 1,0 48a24,24 0,1 1,0 -48z" />
    <path
        android:fillColor="{ink}"
        android:pathData="{path}" />
</vector>
"""


def main() -> None:
    font = instantiateVariableFont(
        TTFont(sys.argv[1]), {"wght": 500, "FILL": 0, "GRAD": 0, "opsz": 24}
    )
    res = Path(__file__).resolve().parent.parent / "android/app/src/main/res"
    for _, (name, cp, light, dark) in FACES.items():
        path = face_path(font, cp)
        for folder, disc, ink in (
            ("drawable", light, ON_LIGHT),
            ("drawable-night", dark, ON_DARK),
        ):
            out = res / folder / f"mood_{name}.xml"
            out.parent.mkdir(exist_ok=True)
            out.write_text(drawable(path, disc, ink))
            print(out.relative_to(res.parent.parent.parent.parent.parent))


if __name__ == "__main__":
    main()
